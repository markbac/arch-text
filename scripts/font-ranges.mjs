// Writes src/font-ranges.ts: the unicode range Excalidraw declares for each font file of the fonts
// arch-text measures with (ADR-007 in docs/decisions.md). A test checks the file still matches the
// installed package, so run this again after upgrading @excalidraw/excalidraw.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const FAMILIES = ['Excalifont', 'Nunito', 'ComicShanns'];

/** Excalidraw's own font-face declarations, read from its unminified build. */
export function readRanges() {
  const dev = path.join(path.dirname(createRequire(import.meta.url).resolve('@excalidraw/excalidraw')), '..', 'dev');
  const code = fs.readdirSync(dev).filter((f) => f.endsWith('.js')).map((f) => fs.readFileSync(path.join(dev, f), 'utf8')).join('\n');
  const google = Object.fromEntries([...(/var GOOGLE_FONTS_RANGES = \{([\s\S]*?)\};/.exec(code)?.[1] ?? '').matchAll(/(\w+): "([^"]+)"/g)].map((m) => [m[1], m[2]]));
  const out = {};
  for (const family of FAMILIES) {
    const block = new RegExp(`var ${family}FontFaces = \\[([\\s\\S]*?)\\n\\];`).exec(code)?.[1];
    if (!block) throw new Error(`No font faces for ${family} in @excalidraw/excalidraw`);
    out[family] = [...block.matchAll(/uri: (\w+),\s*descriptors: \{\s*unicodeRange: (?:"([^"]+)"|GOOGLE_FONTS_RANGES\.(\w+))/g)].map((m) => {
      const file = new RegExp(`var ${m[1]} = "\\./fonts/${family}/([^"]+)"`).exec(code)?.[1];
      const range = m[2] ?? google[m[3]];
      if (!file || !range) throw new Error(`Cannot read the face ${m[1]} of ${family}`);
      return { file, ranges: parseRange(range) };
    });
  }
  return out;
}

/** `U+20-7e, U+a0` as [first, last] code point pairs. */
function parseRange(text) {
  return text.split(',').map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });
}

export function render(ranges) {
  return `// Generated by scripts/font-ranges.mjs from @excalidraw/excalidraw: do not edit.
// The unicode range of each font file, in Excalidraw's order, as [first, last] code points.
export const FONT_RANGES: Record<string, { file: string; ranges: [number, number][] }[]> = {
${Object.entries(ranges)
  .map(([family, faces]) => `  ${family}: [\n${faces.map((f) => `    { file: '${f.file}', ranges: ${JSON.stringify(f.ranges)} },`).join('\n')}\n  ],`)
  .join('\n')}
};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync('src/font-ranges.ts', render(readRanges()));
  console.log('Wrote src/font-ranges.ts.');
}
